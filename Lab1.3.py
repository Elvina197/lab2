# Определение расположения точки А(х,y)

x = float(input("Введите координату х "))
y = float(input("Введите координату у "))
if -1 <= x <= 1 and -4 <= y <= 3:
    print("Принадлежит")
    if 1 <= x <= 5 and y >= -4:
        print("Принадлежит")
        if (5*x + 4*y) <= 9:
            print("Принадлежит")
else:
    print("Не принадлежит")
